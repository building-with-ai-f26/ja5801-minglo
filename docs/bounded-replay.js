/* Shared by the static Product Page and the explicitly enabled localhost demo. */
export function safeReplayPage(value) {
  try {
    const url = new URL(value);
    if (url.username || url.password || url.hash) return null;
    if (url.search && url.search !== "?minglo_analytics_test=1") return null;
    if (
      url.origin === "https://building-with-ai-f26.github.io" &&
      ["/ja5801-minglo/", "/ja5801-minglo/index.html"].includes(url.pathname)
    )
      return {
        url: "https://building-with-ai-f26.github.io/ja5801-minglo/",
        surface: "product_page",
      };
    if (
      ["http://localhost:3000", "http://127.0.0.1:3000"].includes(url.origin) &&
      url.pathname === "/demo/github-profile" &&
      !url.search
    )
      return {
        url: `${url.origin}/demo/github-profile`,
        surface: "local_demo",
      };
  } catch {
    /* Not an approved URL. */
  }
  return null;
}

export function replayEvent(input, token, identity, permitted) {
  const page = safeReplayPage(location.href);
  if (!input || !page || !permitted()) return null;
  const source = input.properties || {};
  const properties = {
    token,
    distinct_id: identity,
    $geoip_disable: true,
    $process_person_profile: false,
    environment: "verification",
    schema_version: 1,
    capture_source: "browser",
    surface: page.surface,
  };
  // Session/window IDs are generated by the SDK, never account or room IDs.
  for (const key of ["$session_id", "$window_id", "$lib", "$lib_version"])
    if (typeof source[key] === "string") properties[key] = source[key];
  if (input.event === "$pageview") {
    properties.$current_url = page.url;
    properties.$pathname = new URL(page.url).pathname;
  } else if (
    input.event === "$snapshot" &&
    Array.isArray(source.$snapshot_data)
  ) {
    // No custom/plugin events (including console and network payloads).
    properties.$snapshot_data = source.$snapshot_data
      .filter((event) => event && [0, 1, 2, 3, 4].includes(event.type))
      .map((event) =>
        event.type === 4
          ? {
              ...event,
              data: {
                width: event.data?.width,
                height: event.data?.height,
                href: page.url,
              },
            }
          : event,
      );
    if (!properties.$snapshot_data.length) return null;
    if (typeof source.$snapshot_bytes === "number")
      properties.$snapshot_bytes = source.$snapshot_bytes;
  } else return null;
  const { $set, $set_once, ...transport } = input;
  return { ...transport, properties };
}

/** @param {(message: string) => void} changed */
export function startBoundedReplay(
  posthog,
  token,
  permitted,
  changed = () => {},
) {
  if (!safeReplayPage(location.href) || !permitted())
    throw new Error("Recording is not allowed here.");
  let active = true;
  const identity = crypto.randomUUID();
  const allowed = () =>
    active &&
    permitted() &&
    !!safeReplayPage(location.href) &&
    !document.hidden;
  const instance = posthog.init(
    token,
    {
      api_host: "https://us.i.posthog.com",
      defaults: "2026-08-30",
      strict_script_versioning: true,
      ip: false,
      autocapture: false,
      capture_pageview: false,
      capture_pageleave: false,
      capture_performance: false,
      capture_exceptions: false,
      capture_dead_clicks: false,
      capture_heatmaps: false,
      rageclick: false,
      disable_session_recording: true,
      disable_surveys: true,
      disable_conversations: true,
      disable_product_tours: true,
      enable_recording_console_log: false,
      advanced_disable_flags: false,
      opt_out_useragent_filter: true,
      persistence: "memory",
      disable_persistence: true,
      save_referrer: false,
      save_campaign_params: false,
      person_profiles: "never",
      request_batching: false,
      bootstrap: { distinctID: identity, isIdentifiedID: false },
      session_recording: {
        maskAllInputs: true,
        maskTextSelector: "*",
        maskAllElementAttributes: true,
        blockSelector:
          "script, iframe, img, video, audio, canvas, object, embed, input[type=hidden], [data-replay-private], .ph-no-capture",
        recordHeaders: false,
        recordBody: false,
        recordCrossOriginIframes: false,
        collectFonts: false,
        slimDOMOptions: "all",
        maskCapturedNetworkRequestFn: () => undefined,
        maskNetworkRequestFn: () => undefined,
      },
      before_send: (event) => replayEvent(event, token, identity, allowed),
      on_request_error: () => {},
      debug: false,
      loaded: (sdk) => {
        if (!allowed()) {
          sdk.opt_out_capturing();
          return;
        }
        sdk.capture("$pageview");
        // Project-side replay must be enabled; this does not bypass that safeguard.
        sdk.startSessionRecording();
      },
    },
    `mingloBoundedReplay_${identity.replaceAll("-", "")}`,
  );
  const stop = () => {
    if (!active) return;
    active = false;
    instance?.stopSessionRecording();
    instance?.opt_out_capturing();
    clearInterval(statusTimer);
    clearTimeout(limit);
    window.removeEventListener("pagehide", stop);
    document.removeEventListener("visibilitychange", visibility);
    document.removeEventListener("click", leave, true);
    changed(
      "Recording stopped. Start again only if you want another demo recording.",
    );
  };
  const visibility = () => {
    if (document.hidden) stop();
  };
  const leave = (event) => {
    if (event.target instanceof Element && event.target.closest("a")) stop();
  };
  const statusTimer = setInterval(() => {
    if (!allowed()) {
      stop();
      return;
    }
    changed(
      instance?.sessionRecordingStarted()
        ? "Recording this demo page. All text, inputs and attributes are masked."
        : "Waiting for PostHog replay configuration. Recording has not started yet.",
    );
  }, 1000);
  const limit = setTimeout(stop, 10 * 60 * 1000);
  window.addEventListener("pagehide", stop);
  document.addEventListener("visibilitychange", visibility);
  document.addEventListener("click", leave, true);
  return stop;
}
